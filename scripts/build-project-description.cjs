/* Preserve the supplied write-up verbatim; add reading sections and linked citations. */
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const source = fs.readFileSync(path.join(root, "content/project-description.txt"), "utf8");
const paragraphs = source.split(/\r?\n/).map(line => line.trim()).filter(Boolean);
const referenceStart = paragraphs.findIndex(line => /^1\. Cai,/.test(line));
const body = paragraphs.slice(0, referenceStart);
if (referenceStart !== 67) throw new Error("Project Description source structure changed; review the section boundaries.");
const escape = value => String(value).replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"})[c]);
const cite = text => escape(text).replace(/\[(\d+(?:,\s*\d+)*)\]/g, (_, group) =>
  `[${group.split(/,\s*/).map(number => `<a class="project-paper-citation" href="#description-ref-${number}" aria-label="Reference ${number}">${number}</a>`).join(", ")}]`);
const groups = [
  ["abstract", "Abstract", 0, 2],
  ["gallbladder-removal", "Gallbladder removal and PCS", 2, 9],
  ["bile-acid-metabolism", "Bile acids and the intestinal microbiome", 9, 18],
  ["selective-modification", "Why selective LCA modification?", 18, 22],
  ["current-treatments", "Current treatments and their limitations", 22, 29],
  ["sulfation-approach", "Our proposed sulfation approach", 29, 37],
  ["btsult-engineering", "From BtSULT to SulFlux", 37, 45],
  ["paps-supply", "PAPS supply and gene regulation", 45, 51],
  ["biochemical-validation", "Testing the proposed mechanism", 51, 55],
  ["probiotic-delivery", "Toward probiotic delivery", 55, 62],
  ["project-outlook", "Research goals and next questions", 62, 67]
];
const sections = groups.map(([id, title, start, end]) => {
  let inList = false;
  let html = "";
  for (const paragraph of body.slice(start, end)) {
    if (paragraph.startsWith("- ")) {
      if (!inList) html += "<ul>";
      inList = true;
      html += `<li>${cite(paragraph.slice(2))}</li>`;
    } else {
      if (inList) html += "</ul>";
      inList = false;
      html += `<p>${cite(paragraph)}</p>`;
    }
  }
  if (inList) html += "</ul>";
  return {id, title, html};
});
const references = JSON.parse(fs.readFileSync(path.join(root, "content/project-description-references.json"), "utf8"))
  .map((reference, index) => ({number: index + 1, supplementary: index >= 11,
    html: `${escape(reference.author)} <a href="${escape(reference.url)}" target="_blank" rel="noopener noreferrer">“${escape(reference.title)}.”</a> <em>${escape(reference.publication)}</em>${reference.details ? `, ${escape(reference.details)}` : ""}.${reference.note ? ` <span class="project-reference-note">${escape(reference.note)}</span>` : ""}`}));
const output = `/* Generated by scripts/build-project-description.cjs. Edit content/project-description.txt and its references. */\n(function () {\n  "use strict";\n  const page = window.SITE_DATA?.pages["project-description"];\n  if (!page) return;\n  page.description = ${JSON.stringify({sections, references}, null, 2)};\n})();\n`;
const destination = path.join(root, "js/project-overview-content.js");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== output) throw new Error("Project Description is stale. Run node scripts/build-project-description.cjs.");
} else {
  fs.writeFileSync(destination, output);
}
console.log(`Project Description: ${body.length} content blocks, ${sections.length} sections, ${references.length} references.`);
